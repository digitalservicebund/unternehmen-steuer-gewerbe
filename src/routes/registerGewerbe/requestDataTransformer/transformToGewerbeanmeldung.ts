import {
  type CreateGewerbeanmeldungXmlData,
  type TransportMethod,
} from "../../../xmlBuilders/xGewerbeordnung/gewerbeanmeldung";
import { type RegisterGewerbeRequest } from "../registerGewerbeInterfaces";
import { type GewerbeRoutingInfo } from "../getGewerbeRoutingInfo";
import { type Nachweisdokument } from "../../../xmlBuilders/xGewerbeordnung/buildingBlocks/nachweisdokument";
import {
  formatTelefonnummerDIN5008,
  getBetriebsAdresse,
  splitStrasseHausnummer,
} from "../../../helpers/formFieldTransformations";
import {
  VERTRAUENSNIVEAU,
  RECHTSFORM,
  STAATSANGEHOERIGKEIT,
  STAATSANGEHOERIGKEIT_ICAO,
  HAMBURG_GEMEINDESCHLUESSEL,
  HAMBURG_STADTBEZIRK_PLZ,
  GRUNDANMELDUNGSSCHLUESSEL,
  ART_BETRIEBSSTAETTE,
  BETEILIGUNG_OEFFENTLICHE_HAND,
  GESCHLECHT,
} from "./xGewerbeordnungCodes";
import { Anschrift } from "../../../xmlBuilders/xGewerbeordnung/buildingBlocks/anschrift";

const PDF_RECEIPT_FILE_NAME = "gewerbeanmeldung-beleg.pdf";

/**
 * The PDF document, which is generated by the online service itself and sent as an attachment.
 * OK.KOMM extracts the OSCI-Ref-ID of the attachment from its filename, and the
 * transport profile requires that the Ref-ID == dokumentid – therefore, the document ID is
 * the filename.
 */
export const PDF_RECEIPT_NACHWEISDOKUMENT = {
  dokumentid: PDF_RECEIPT_FILE_NAME,
  dateiname: PDF_RECEIPT_FILE_NAME,
  mimetype: "application/pdf",
  kategorie: "Antrag im Original",
} as const satisfies Nachweisdokument;

// xGewerbeordnung has no separate field for the Hausnummer-Zusatz, so it is appended to
// hausnummerVon directly (e.g. "21a")
function joinHausnummerUndZusatz(hausnummer?: string, zusatz?: string): string {
  return `${hausnummer ?? ""}${zusatz ?? ""}`;
}

function createBetriebsAnschrift(data: RegisterGewerbeRequest): Anschrift {
  const { adresse, adresseAbweichend } = data.unternehmensDaten;
  const { strasse, hausnummer, hausnummerBis, hausnummerZusatz, postleitzahl, ort } =
    getBetriebsAdresse({
      adresse,
      adresseAbweichend,
      persönlicheAdresse: data.persönlicheDaten.adresse,
    });
  return {
    strasse,
    hausnummerVon: joinHausnummerUndZusatz(hausnummer, hausnummerZusatz),
    hausnummerBis,
    postleitzahl,
    ort,
  };
}

/**
 * Resolves the Gemeindeschlüssel-Ergänzung Code for Hamburg.
 * Returns undefined for non-Hamburg municipalities
 */
function getGemeindeschluesselErgaenzung(gemeindeSchluessel: string, betriebsPlz?: string) {
  if (betriebsPlz === undefined || gemeindeSchluessel !== HAMBURG_GEMEINDESCHLUESSEL) {
    return undefined;
  }

  for (const [gemeindeschluesselErgaenzung, plzList] of Object.entries(HAMBURG_STADTBEZIRK_PLZ)) {
    if (plzList.includes(betriebsPlz)) {
      return gemeindeschluesselErgaenzung;
    }
  }

  return undefined;
}

// Transforms a RegisterGewerbeRequest into a complete Gewerbeanmeldung structure.
// NOTE: several values are hardcoded placeholders and will be generated / fetched from other sources later.
export function transformToGewerbeanmeldung(
  data: RegisterGewerbeRequest,
  routingInfo: GewerbeRoutingInfo,
  transportMethod: TransportMethod,
): CreateGewerbeanmeldungXmlData {
  const personStrasseHausnummer = splitStrasseHausnummer(
    data.persönlicheDaten.adresse.strasseUndHausnummer,
  );

  const betriebsAnschrift = createBetriebsAnschrift(data);

  const { staatsangehörigkeitIcao } = data.persönlicheDaten;
  const staatsangehoerigkeitCode = staatsangehörigkeitIcao
    ? STAATSANGEHOERIGKEIT_ICAO[staatsangehörigkeitIcao]
    : STAATSANGEHOERIGKEIT[data.persönlicheDaten.staatsangehörigkeit];

  const gemeindeSchluessel = routingInfo.ags;
  const gewerbeamtKennung = `MELDID:${gemeindeSchluessel}`;
  const gewerbeamtName = routingInfo.gewerbeamt.name || "Gewerbeamt";
  const personId = randomUUID();

  return {
    nachrichtenkopf: {
      nachrichtenUUID: randomUUID(),
      erstellungszeitpunkt: new Date().toISOString(),
      leser: { kennung: gewerbeamtKennung, name: gewerbeamtName },
      autor: { kennung: "ds:schnellergruenden", name: "Schneller Gründen" },
    },
    autor: { kennung: gewerbeamtKennung, name: gewerbeamtName },
    anzeigerenderId: personId,
    handelndePersonId: personId,
    handelndePersonVertrauensniveauCode: VERTRAUENSNIVEAU[data.persönlicheDaten.vertrauensniveau],
    // only the OSCI transport carries the PDF receipt along, and the message may only declare
    // the Anlage where it is actually sent along (see submitViaOsci)
    nachweisdokumentOnlinedienst:
      transportMethod === "osci" ? PDF_RECEIPT_NACHWEISDOKUMENT : undefined,
    satzErstellung: new Date().toISOString(),
    ereigniszeitpunkt: new Date().toISOString(),
    istStorno: false,
    gemeindeSchluessel,
    gemeindeschluesselErgaenzung: getGemeindeschluesselErgaenzung(
      gemeindeSchluessel,
      betriebsAnschrift.postleitzahl,
    ),
    uuid: randomUUID(),
    gueltigAb: data.unternehmensDaten.anmeldedatumGewerbeamt,
    datumMeldung: new Date().toISOString().split("T")[0]!,
    grundAnmeldungSchluessel: GRUNDANMELDUNGSSCHLUESSEL[data.unternehmensDaten.gründungsart],
    // SCH-0007: may only stay empty while gründungsart is "neugründung" and artBetriebsstaette is
    // "hauptniederlassung" (or istReisegewerbe is true) — opening any of those makes it mandatory.
    bisherigeUnfallversicherung: undefined,
    gewerbebetrieb: {
      gewerbebetriebID: randomUUID(),
      // The Gewerbeamt assigns this number itself; not required for ext.0400 messages
      gemeindeMeldungNr: undefined,
      rechtsformcode: RECHTSFORM[data.unternehmensDaten.rechtsform],
      // SCH-0205: eingetragenerName must not be set for nichtEingetragenesEinzelunternehmen
      eingetragenerName: undefined,
      geschaeftsbezeichnung: data.unternehmensDaten.geschäftsbezeichnung,
      betriebsstaette: {
        artBetriebsstaette: ART_BETRIEBSSTAETTE[data.unternehmensDaten.artBetriebsstaette],
        anschrift: betriebsAnschrift,
      },
      taetigkeitenGesamt: {
        schwerpunkt: {
          taetigkeitSchwerpunkt: data.unternehmensDaten.tätigkeitsbeschreibung,
        },
      },
      istNebenerwerb: data.unternehmensDaten.gewerbeart === "nebengewerbe",
      anzahlVollzeitBeschaeftigte: data.unternehmensDaten.anzahlVollzeitBeschaeftigte,
      anzahlTeilzeitBeschaeftigte: data.unternehmensDaten.anzahlTeilzeitBeschaeftigte,
      istReisegewerbe: data.unternehmensDaten.istReisegewerbe,
      beteiligungOeffentlicheHand:
        BETEILIGUNG_OEFFENTLICHE_HAND[data.unternehmensDaten.beteiligungOeffentlicheHand],
      betriebArt: {
        industrie: data.unternehmensDaten.tätigkeitsbereich === "industrie",
        handwerk: data.unternehmensDaten.tätigkeitsbereich === "handwerk",
        handel: data.unternehmensDaten.tätigkeitsbereich === "handel",
        sonstiges: data.unternehmensDaten.tätigkeitsbereich === "sonstiges",
      },
    },
    referenzierteSubjekte: {
      natuerlichePerson: [
        {
          id: personId,
          name: {
            familienname: data.persönlicheDaten.nachname,
            geburtsname: data.persönlicheDaten.geburtsname,
            vornamen: data.persönlicheDaten.vorname,
          },
          geburt: {
            geburtsdatum: data.persönlicheDaten.geburtsdatum,
            ort: data.persönlicheDaten.geburtsort ?? "keine Angabe",
            staat: data.persönlicheDaten.geburtsland ?? "keine Angabe",
          },
          geschlecht: GESCHLECHT[data.persönlicheDaten.geschlecht],
          staatsangehoerigkeit: staatsangehoerigkeitCode,
          anschrift: {
            strasse: personStrasseHausnummer.strasse,
            hausnummerVon: joinHausnummerUndZusatz(
              personStrasseHausnummer.hausnummer,
              personStrasseHausnummer.hausnummerZusatz,
            ),
            hausnummerBis: personStrasseHausnummer.hausnummerBis,
            postleitzahl: data.persönlicheDaten.adresse.postleitzahl,
            ort: data.persönlicheDaten.adresse.ort,
          },
          kommunikation: {
            telefon: formatTelefonnummerDIN5008(data.persönlicheDaten.telefon),
            email: data.persönlicheDaten.email,
          },
        },
      ],
    },
  };
}
